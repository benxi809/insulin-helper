/// AI 眼镜品牌
enum AIGlassesBrand {
  none,
  mock,
  rayneo,    // 雷鸟X2
  inmo,      // INMO Air
  xiaomi,    // 小米智能眼镜
  other,     // 其他Android眼镜
}

extension AIGlassesBrandExtension on AIGlassesBrand {
  String get displayName {
    switch (this) {
      case AIGlassesBrand.none: return '未选择';
      case AIGlassesBrand.mock: return '模拟数据';
      case AIGlassesBrand.rayneo: return '雷鸟 X2';
      case AIGlassesBrand.inmo: return 'INMO Air';
      case AIGlassesBrand.xiaomi: return '小米智能眼镜';
      case AIGlassesBrand.other: return '其他安卓眼镜';
    }
  }

  String get shortName {
    switch (this) {
      case AIGlassesBrand.none: return 'none';
      case AIGlassesBrand.mock: return 'mock';
      case AIGlassesBrand.rayneo: return 'rayneo';
      case AIGlassesBrand.inmo: return 'inmo';
      case AIGlassesBrand.xiaomi: return 'xiaomi';
      case AIGlassesBrand.other: return 'other';
    }
  }

  static AIGlassesBrand fromShortName(String name) {
    for (final b in AIGlassesBrand.values) {
      if (b.shortName == name) return b;
    }
    return AIGlassesBrand.none;
  }

  /// 是否需要配置
  bool get needsConfig {
    switch (this) {
      case AIGlassesBrand.none:
      case AIGlassesBrand.mock:
        return false;
      default:
        return true;
    }
  }
}

/// AI 眼镜配置
class AIGlassesConfig {
  String deviceType;    // brand shortName
  String displayName;
  bool isConnected;
  String? ipAddress;    // 眼镜IP地址（局域网连接）
  int port;             // 连接端口
  String? apiKey;       // API密钥

  AIGlassesConfig({
    this.deviceType = 'none',
    this.displayName = '未连接',
    this.isConnected = false,
    this.ipAddress,
    this.port = 8080,
    this.apiKey,
  });

  Map<String, dynamic> toMap() => {
    'id': 1,
    'deviceType': deviceType,
    'displayName': displayName,
    'isConnected': isConnected ? 1 : 0,
    'ipAddress': ipAddress,
    'port': port,
    'apiKey': apiKey,
  };

  factory AIGlassesConfig.fromMap(Map<String, dynamic> map) => AIGlassesConfig(
    deviceType: map['deviceType'] as String? ?? 'none',
    displayName: map['displayName'] as String? ?? '未连接',
    isConnected: (map['isConnected'] as int?) == 1,
    ipAddress: map['ipAddress'] as String?,
    port: map['port'] as int? ?? 8080,
    apiKey: map['apiKey'] as String?,
  );
}

/// AI 眼镜拍照结果
class GlassesPhotoResult {
  final Uint8List? imageBytes;
  final String? error;
  final bool success;

  GlassesPhotoResult({
    this.imageBytes,
    this.error,
    required this.success,
  });
}

/// AI 眼镜连接器接口
abstract class AIGlassesConnector {
  /// 连接眼镜
  Future<bool> connect(Map<String, String> credentials);

  /// 断开连接
  Future<void> disconnect();

  /// 拍照（手动触发）
  Future<GlassesPhotoResult> takePhoto();

  /// 是否已连接
  bool get isConnected;

  /// 连接器名称
  String get name;
}

