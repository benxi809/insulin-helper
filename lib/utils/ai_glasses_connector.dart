  static AIGlassesConnector create(AIGlassesBrand brand) {
    switch (brand) {
      case AIGlassesBrand.mock:
        return MockAIGlassesConnector();
      case AIGlassesBrand.none:
        return MockAIGlassesConnector(); // 默认使用 Mock
      case AIGlassesBrand.rayneo:
      case AIGlassesBrand.inmo:
      case AIGlassesBrand.xiaomi:
      case AIGlassesBrand.other:
        return AndroidGlassesConnector();
    }
  }
}
